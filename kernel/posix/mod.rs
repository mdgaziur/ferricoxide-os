//! POSIX error codes used inside the kernel.
//!
//! This file provides a `PosixError` enum listing common POSIX errno
//! names and a small helper to get the human-readable description.

#![allow(missing_docs)]

// Default file and dir permissions, taken from Linux
// This may change in future
pub const DEFAULT_FILE_PERMISSIONS: u16 = 0o644;
pub const DEFAULT_DIR_PERMISSIONS: u16 = 0o755;

